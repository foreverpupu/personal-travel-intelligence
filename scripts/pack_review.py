#!/usr/bin/env python3
"""Build a review bundle: tracked files only, private data excluded, self-checkable.

Why: handing a raw repository path to a cloud-backed agent lets it read
travel-data/USER-preferences.md. This copies exactly the files that are safe to
publish, keeps the directory layout so scripts still run, and records hashes so
an external reviewer can prove what it looked at.

Usage: python3 scripts/pack_review.py [--out DIR]
"""
import hashlib
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION = open(os.path.join(ROOT, "VERSION"), encoding="utf-8").read().strip()
DEFAULT_OUT = os.path.join(ROOT, "dist", f"review-{VERSION}")
# Tracked files are public by construction; these are belt-and-braces.
DENY_PREFIX = ("travel-data/", "project-edition/", "_inbox/", "dist/", ".git/")


def sh(*args):
    return subprocess.run(args, cwd=ROOT, capture_output=True, text=True).stdout.strip()


def fill_prompt(bundle, commit):
    """Fill the main prompt from the doc so the reviewer never sees a placeholder."""
    doc = os.path.join(ROOT, "docs", "validation", "VALIDATION-PROMPT.md")
    text = open(doc, encoding="utf-8").read()
    match = re.search(r"```text\n(.*?)```", text, re.S)
    if not match:
        return "prompt template not found — read docs/validation/VALIDATION-PROMPT.md"
    body = match.group(1)
    body = body.replace("{BUNDLE}", bundle).replace("{REPO}", ROOT).replace("{版本}", VERSION)
    header = (
        f"<!-- generated by scripts/pack_review.py at commit {commit} -->\n"
        f"<!-- bundle: {bundle} -->\n\n"
        "把下面整段交给评审模型。路径已填好，不要再替换。\n\n"
    )
    return header + "```text\n" + body.strip() + "\n```\n"


def main():
    out = DEFAULT_OUT
    if "--out" in sys.argv:
        out = os.path.abspath(sys.argv[sys.argv.index("--out") + 1])
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)

    files = [p for p in sh("git", "ls-files").splitlines() if os.path.isfile(os.path.join(ROOT, p))]
    files = [p for p in files if not p.startswith(DENY_PREFIX)]
    # Rules-only Project files so parity can be judged; the patch README and
    # diffs stay out because they describe personal trips.
    # Every Project rule file, so the bundle can reproduce the upload gate.
    # Notes and the private preference file stay out.
    proj = os.path.join(ROOT, "project-edition")
    skip = {"README.md", "USER-preferences.md", "LOCAL-NOTES.md"}
    if os.path.isdir(proj):
        files += [os.path.join("project-edition", f) for f in sorted(os.listdir(proj))
                  if f.endswith(".md") and f not in skip and os.path.isfile(os.path.join(proj, f))]
    rows = []
    for rel in files:
        src = os.path.join(ROOT, rel)
        dst = os.path.join(out, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
        digest = hashlib.sha256(open(src, "rb").read()).hexdigest()
        rows.append((rel, digest, sum(1 for _ in open(src, encoding="utf-8", errors="replace"))))

    commit = sh("git", "rev-parse", "HEAD")
    branch = sh("git", "rev-parse", "--abbrev-ref", "HEAD")
    with open(os.path.join(out, "MANIFEST.sha256"), "w", encoding="utf-8") as fh:
        for rel, digest, _ in rows:
            fh.write(f"{digest}  {rel}\n")

    readme = f"""# PTI review bundle — {VERSION}

Purpose: everything an external reviewer needs, and nothing that is private.

- commit: `{commit}`
- branch: `{branch}`
- files: {len(rows)}
- generated by: `scripts/pack_review.py`

## What is deliberately absent

`travel-data/` (personal preferences and trip ledgers), `_inbox/`, `dist/`,
and the Project edition's `USER-preferences.md`. If a review requires them,
the owner must supply a redacted copy explicitly.

## How to verify this bundle

```bash
cd <this directory>
shasum -a 256 -c MANIFEST.sha256
python3 scripts/check_all.py
```

`check_all.py` is self-contained (stdlib only) and must exit 0. If it fails,
the bundle is inconsistent before any judgement is made.

## How to review

Read `docs/validation/VALIDATION-PROMPT.md` and follow it. Do not read outside
this directory. Do not modify files in place; copy to a scratch directory first.
"""
    with open(os.path.join(out, "REVIEW-README.md"), "w", encoding="utf-8") as fh:
        fh.write(readme)

    prompt = fill_prompt(out, commit)
    with open(os.path.join(out, "REVIEW-PROMPT.md"), "w", encoding="utf-8") as fh:
        fh.write(prompt)

    total = sum(os.path.getsize(os.path.join(out, r)) for r, _, _ in rows)
    print(f"bundle : {os.path.relpath(out, ROOT)}")
    print(f"files  : {len(rows)} ({total/1024:.0f} KB)")
    print(f"commit : {commit}")
    print(f"check  : python3 scripts/check_all.py  (run inside the bundle)")
    print(f"prompt : dist/review-{VERSION}/REVIEW-PROMPT.md  (paths already filled)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
